#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	int	i;

	if (n == -2147483648)
	{
		write(fd, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		ft_putchar_fd('-', fd);
		n = -n;
	}
	i = 1;
	while (n / i >= 10)
	{
		i = i * 10;
	}
	while (i > 0)
	{
		ft_putchar_fd((n / i + '0'), fd);
		n = n % i;
		i = i / 10;
	}
}
